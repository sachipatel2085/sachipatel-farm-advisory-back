/* Auto-seed default general crop tasks into the database if empty */
export const seedDefaultGeneralCropTasks = async () => {
  try {
    const count = await GeneralCropTask.countDocuments();
    if (count > 0) return;

    const cropsToSeed = [
      { name: "Tomato", duration: 120 },
      { name: "Wheat", duration: 130 },
      { name: "Cotton", duration: 150 },
      { name: "Potato", duration: 100 },
      { name: "Chilli", duration: 120 },
      { name: "Rice", duration: 120 },
      { name: "Mustard", duration: 110 },
    ];

    const tasksToInsert = [];
    for (const c of cropsToSeed) {
      const template = getCropSpecificAgronomicTemplate(c.name, c.duration);
      for (const t of template) {
        tasksToInsert.push({
          cropName: c.name,
          title: t.title,
          dayOffset: t.dayOffset,
          activityType: t.activityType,
          priority: t.priority || "medium",
          growthStage: t.growthStage || "Vegetative",
          dosage: t.dosage || "",
          stageWarning: t.stageWarning || "",
          targetPests: t.targetPests || [],
          notes: t.notes || "",
          estimatedCost: t.cost || 0,
          active: true,
        });
      }
    }

    if (tasksToInsert.length > 0) {
      await GeneralCropTask.insertMany(tasksToInsert);
      console.log(
        `Seeded ${tasksToInsert.length} standard general crop tasks for Tomato, Wheat, Cotton, Potato, Chilli, Rice, and Mustard.`
      );
    }
  } catch (err) {
    console.warn("General crop tasks auto-seed error:", err.message);
  }
};

/* Auto-generate standard agronomic schedule for a crop based on Admin & Moderator General Tasks */
export const generateStandardSchedule = async (req, res) => {
  try {
    const userId = req.user._id;
    const { cropId } = req.params;

    const verification = await verifyCropOwnership(cropId, userId);
    if (verification.error) {
      return res
        .status(verification.status)
        .json({ message: verification.error });
    }

    const { crop, farm } = verification;
    const sowing = new Date(crop.sowingDate);

    // Fetch existing user activities for this crop
    const existingActivities = await CropActivity.find({
      crop: crop._id,
      user: userId,
    })
      .populate("crop", "cropName variety sowingDate expectedDurationDays status")
      .populate("farm", "farmName")
      .sort({ dueDate: 1 });

    // 1. Fetch Admin & Moderator configured General Tasks specifically for this crop!
    const generalTasks = await GeneralCropTask.find({
      cropName: new RegExp(`^${crop.cropName.trim()}$`, "i"),
      active: true,
    })
      .sort({ dayOffset: 1 })
      .lean();

    // 2. If NO general tasks configured for this crop by Admin or Moderator
    if (generalTasks.length === 0) {
      return res.status(200).json({
        isAvailable: false,
        addedCount: 0,
        message: `Standard schedule is not available for ${crop.cropName}. General crop tasks have not been configured for this crop by administrators or moderators yet. You can add your own custom tasks below.`,
        cropName: crop.cropName,
        activities: existingActivities,
      });
    }

    // 3. Populate existing titles to avoid duplicate entries
    const existingTitles = new Set(
      existingActivities.map((a) => a.title.toLowerCase().trim())
    );

    const newActivitiesToInsert = [];
    for (const t of generalTasks) {
      if (existingTitles.has(t.title.toLowerCase().trim())) continue;

      const dueDate = new Date(
        sowing.getTime() + (t.dayOffset || 0) * 24 * 60 * 60 * 1000
      );
      newActivitiesToInsert.push({
        user: userId,
        crop: crop._id,
        farm: farm._id,
        field: crop.field || null,
        title: t.title,
        activityType: t.activityType,
        dueDate,
        priority: t.priority || "medium",
        notes: t.notes || "",
        growthStage: t.growthStage || "",
        stageWarning: t.stageWarning || "",
        dosage: t.dosage || "",
        targetPests: t.targetPests || [],
        cost: t.estimatedCost || 0,
        autoGenerated: true,
        isGeneralTask: true,
        status: "pending",
      });
    }

    if (newActivitiesToInsert.length > 0) {
      await CropActivity.insertMany(newActivitiesToInsert);
    }

    const allActivities = await CropActivity.find({
      crop: crop._id,
      user: userId,
    })
      .populate("crop", "cropName variety sowingDate expectedDurationDays status")
      .populate("farm", "farmName")
      .sort({ dueDate: 1 });

    res.json({
      isAvailable: true,
      message: `Generated ${newActivitiesToInsert.length} standard general tasks for ${crop.cropName}`,
      addedCount: newActivitiesToInsert.length,
      cropName: crop.cropName,
      activities: allActivities,
    });
  } catch (error) {
    console.error("generateStandardSchedule error:", error);
    res.status(500).json({ message: error.message });
  }
};
