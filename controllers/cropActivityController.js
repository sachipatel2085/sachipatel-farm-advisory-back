/* Helper: Verify Crop ownership */
const verifyCropOwnership = async (cropId, userId) => {
  const crop = await Crop.findOne(buildIdOrSlugQuery(cropId));
  if (!crop) return { error: "Crop not found", status: 404 };

  let farm = null;
  if (crop.field) {
    const field = await Field.findById(crop.field);
    if (field && field.farm) {
      farm = await Farm.findById(field.farm);
    }
  }
  if (!farm && crop.farm) {
    farm = await Farm.findById(crop.farm);
  }

  if (!farm) {
    return { error: "Associated farm not found", status: 404 };
  }

  if (farm.user.toString() !== userId.toString()) {
    return { error: "Not authorized", status: 403 };
  }

  return { crop, farm };
};

/* Create a new activity manually */
export const createActivity = async (req, res) => {
  try {
    const userId = req.user._id;
    const {
      cropId,
      title,
      activityType,
      dueDate,
      priority,
      notes,
      cost,
      growthStage,
      stageWarning,
      dosage,
      targetPests,
    } = req.body;

    if (!cropId || !title || !dueDate) {
      return res.status(400).json({
        message: "cropId, title, and dueDate are required fields.",
      });
    }

    const verification = await verifyCropOwnership(cropId, userId);
    if (verification.error) {
      return res
        .status(verification.status)
        .json({ message: verification.error });
    }

    const { crop, farm } = verification;

    const activity = await CropActivity.create({
      user: userId,
      crop: crop._id,
      farm: farm._id,
      field: crop.field || null,
      title: title.trim(),
      activityType: activityType || "general",
      dueDate: new Date(dueDate),
      priority: priority || "medium",
      notes: notes || "",
      cost: Number(cost) || 0,
      growthStage: growthStage || "",
      stageWarning: stageWarning || "",
      dosage: dosage || "",
      targetPests: Array.isArray(targetPests) ? targetPests : [],
      autoGenerated: false,
      isGeneralTask: false,
    });

    const populated = await CropActivity.findById(activity._id)
      .populate("crop", "cropName variety sowingDate expectedDurationDays status")
      .populate("farm", "farmName");

    res.status(201).json({
      message: "Activity created successfully",
      activity: populated,
    });
  } catch (error) {
    console.error("createActivity error:", error);
    res.status(500).json({ message: error.message });
  }
};

/* Get all activities for the logged-in user with rich filtering & stats */
export const getAllUserActivities = async (req, res) => {
  try {
    const userId = req.user._id;
    const {
      cropId,
      activityType,
      status,
      priority,
      startDate,
      endDate,
      timeframe,
    } = req.query;

    const filter = { user: userId };

    if (cropId) {
      filter.crop = cropId;
    }

    if (activityType && activityType !== "all") {
      filter.activityType = activityType;
    }

    if (status && status !== "all") {
      filter.status = status;
    }

    if (priority && priority !== "all") {
      filter.priority = priority;
    }

    const now = new Date();
    const startOfToday = new Date(now.getFullYear(), now.getMonth(), now.getDate());
    const endOfToday = new Date(now.getFullYear(), now.getMonth(), now.getDate(), 23, 59, 59, 999);

    if (timeframe === "today") {
      filter.dueDate = { $gte: startOfToday, $lte: endOfToday };
    } else if (timeframe === "upcoming") {
      const nextWeek = new Date(startOfToday.getTime() + 7 * 24 * 60 * 60 * 1000);
      filter.dueDate = { $gte: startOfToday, $lte: nextWeek };
      filter.status = "pending";
    } else if (timeframe === "overdue") {
      filter.dueDate = { $lt: startOfToday };
      filter.status = "pending";
    } else if (startDate || endDate) {
      filter.dueDate = {};
      if (startDate) filter.dueDate.$gte = new Date(startDate);
      if (endDate) filter.dueDate.$lte = new Date(endDate);
    }

    const activities = await CropActivity.find(filter)
      .populate("crop", "cropName variety sowingDate expectedDurationDays status")
      .populate("farm", "farmName")
      .populate("field", "name")
      .sort({ dueDate: 1 })
      .lean();

    const allUserActs = await CropActivity.find({ user: userId }).lean();

    let pendingCount = 0;
    let completedCount = 0;
    let overdueCount = 0;
    let todayCount = 0;
    const typeCounts = {
      fertilizer: 0,
      spray: 0,
      irrigation: 0,
      weeding: 0,
      harvest: 0,
      scouting: 0,
      other: 0,
    };

    allUserActs.forEach((act) => {
      const due = new Date(act.dueDate);
      if (act.status === "completed") {
        completedCount++;
      } else {
        pendingCount++;
        if (due < startOfToday) {
          overdueCount++;
        }
      }

      if (due >= startOfToday && due <= endOfToday) {
        todayCount++;
      }

      const t = act.activityType;
      if (typeCounts[t] !== undefined) {
        typeCounts[t]++;
      } else {
        typeCounts.other++;
      }
    });

    res.json({
      stats: {
        total: allUserActs.length,
        pendingCount,
        completedCount,
        overdueCount,
        todayCount,
        typeCounts,
      },
      activities,
    });
  } catch (error) {
    console.error("getAllUserActivities error:", error);
    res.status(500).json({ message: error.message });
  }
};

/* Get activities for a specific crop */
export const getCropActivities = async (req, res) => {
  try {
    const userId = req.user._id;
    const { cropId } = req.params;

    const verification = await verifyCropOwnership(cropId, userId);
    if (verification.error) {
      return res
        .status(verification.status)
        .json({ message: verification.error });
    }

    const activities = await CropActivity.find({
      crop: verification.crop._id,
      user: userId,
    })
      .populate("crop", "cropName variety sowingDate expectedDurationDays status")
      .populate("farm", "farmName")
      .sort({ dueDate: 1 })
      .lean();

    const pending = activities.filter((a) => a.status === "pending").length;
    const completed = activities.filter((a) => a.status === "completed").length;

    res.json({
      cropId,
      cropName: verification.crop.cropName,
      stats: {
        total: activities.length,
        pending,
        completed,
        completionRate:
          activities.length > 0
            ? Math.round((completed / activities.length) * 100)
            : 0,
      },
      activities,
    });
  } catch (error) {
    console.error("getCropActivities error:", error);
    res.status(500).json({ message: error.message });
  }
};

/* Update an existing activity */
export const updateActivity = async (req, res) => {
  try {
    const userId = req.user._id;
    const { id } = req.params;
    const {
      title,
      activityType,
      dueDate,
      priority,
      notes,
      cost,
      status,
      growthStage,
      stageWarning,
      dosage,
      targetPests,
    } = req.body;

    const activity = await CropActivity.findOne({ _id: id, user: userId });
    if (!activity) {
      return res.status(404).json({ message: "Activity not found" });
    }

    if (title !== undefined) activity.title = title.trim();
    if (activityType !== undefined) activity.activityType = activityType;
    if (dueDate !== undefined) activity.dueDate = new Date(dueDate);
    if (priority !== undefined) activity.priority = priority;
    if (notes !== undefined) activity.notes = notes;
    if (cost !== undefined) activity.cost = Number(cost) || 0;
    if (growthStage !== undefined) activity.growthStage = growthStage;
    if (stageWarning !== undefined) activity.stageWarning = stageWarning;
    if (dosage !== undefined) activity.dosage = dosage;
    if (targetPests !== undefined) activity.targetPests = Array.isArray(targetPests) ? targetPests : [];

    if (status !== undefined) {
      activity.status = status;
      if (status === "completed" && !activity.completedDate) {
        activity.completedDate = new Date();
      } else if (status === "pending") {
        activity.completedDate = null;
      }
    }

    await activity.save();

    const updated = await CropActivity.findById(activity._id)
      .populate("crop", "cropName variety sowingDate expectedDurationDays status")
      .populate("farm", "farmName");

    res.json({
      message: "Activity updated successfully",
      activity: updated,
    });
  } catch (error) {
    console.error("updateActivity error:", error);
    res.status(500).json({ message: error.message });
  }
};

/* Toggle completion status with one click */
export const toggleActivityStatus = async (req, res) => {
  try {
    const userId = req.user._id;
    const { id } = req.params;

    const activity = await CropActivity.findOne({ _id: id, user: userId });
    if (!activity) {
      return res.status(404).json({ message: "Activity not found" });
    }

    if (activity.status === "completed") {
      activity.status = "pending";
      activity.completedDate = null;
    } else {
      activity.status = "completed";
      activity.completedDate = new Date();
    }

    await activity.save();

    const updated = await CropActivity.findById(activity._id)
      .populate("crop", "cropName variety sowingDate expectedDurationDays status")
      .populate("farm", "farmName");

    res.json({
      message: `Activity marked as ${activity.status}`,
      activity: updated,
    });
  } catch (error) {
    console.error("toggleActivityStatus error:", error);
    res.status(500).json({ message: error.message });
  }
};

/* Delete an activity */
