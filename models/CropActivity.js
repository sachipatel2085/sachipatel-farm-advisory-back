import mongoose from "mongoose";

const cropActivitySchema = new mongoose.Schema(
  {
    user: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "User",
      required: true,
      index: true,
    },
    crop: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "Crop",
      required: true,
      index: true,
    },
    farm: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "Farm",
      default: null,
    },
    field: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "Field",
      default: null,
    },
    title: {
      type: String,
      required: true,
      trim: true,
    },
    activityType: {
      type: String,
      enum: [
        "fertilizer",
        "spray",
        "irrigation",
        "weeding",
        "harvest",
        "scouting",
        "soil_test",
        "general",
      ],
      default: "general",
      required: true,
      index: true,
    },
    dueDate: {
      type: Date,
      required: true,
      index: true,
    },
    completedDate: {
      type: Date,
      default: null,
    },
    status: {
      type: String,
      enum: ["pending", "in_progress", "completed", "cancelled"],
      default: "pending",
      index: true,
    },
    priority: {
      type: String,
      enum: ["high", "medium", "low"],
      default: "medium",
    },
    notes: {
      type: String,
      default: "",
    },
    cost: {
      type: Number,
      default: 0,
    },
    growthStage: {
      type: String,
      default: "",
    },
    // Enhanced agronomic fields for A-to-Z suggestions & warnings
    stageWarning: {
      type: String,
      default: "",
    },
    dosage: {
      type: String,
      default: "",
    },
    targetPests: {
      type: [String],
      default: [],
    },
    autoGenerated: {
      type: Boolean,
      default: false,
    },
    isGeneralTask: {
      type: Boolean,
      default: false,
      index: true,
    },
  },
  { timestamps: true }
);

export default mongoose.model("CropActivity", cropActivitySchema);
